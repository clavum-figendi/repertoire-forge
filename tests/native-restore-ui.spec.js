import {test,expect} from '@playwright/test';
const fixture=process.env.NATIVE_BACKUP;
test('restores a real native Stockfish backup for Memorize and Play',async({page})=>{
 test.skip(!fixture,'Set NATIVE_BACKUP to a JSON backup generated by the native CLI');
 await page.goto(process.env.UI_URL||'http://127.0.0.1:4274');
 await page.locator('[data-workspace="Export"]').click();
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('#restore-file').setInputFiles(fixture);
 await expect(page.getByRole('status')).toContainText('Backup restored');
 await page.locator('[data-workspace="Memorize"]').click();
 await expect(page.getByRole('button',{name:/Reveal answer/})).toBeVisible();
 await page.locator('[data-workspace="Play"]').click();
 await page.locator('[data-action="start-drill"]').click();
 await expect(page.getByRole('button',{name:'Restart drill'})).toBeVisible();
});
